<#
.SYNOPSIS
    Generates a vcpkg triplet for each Qt kit installed on this machine.

.DESCRIPTION
    DsQt is built from source against your own Qt kit. vcpkg decides whether a
    cached build can be reused by hashing, among other things, the text of the
    triplet file. Writing the Qt version into the triplet is therefore what
    keeps the binary cache honest: one cache entry per
    (DsQt version x compiler x Qt kit), and no chance of picking up binaries
    that were compiled against a different Qt.

    Run this once after installing or updating a Qt kit.

    Because the triplet text is hashed, the generated file must match the one
    committed under triplets/ byte for byte, or the same Qt kit would end up
    with two different cache entries. Both come from the same template below.

    NOTE: this file is deliberately pure ASCII. Windows PowerShell 5.1 reads a
    BOM-less .ps1 as the ANSI code page, and UTF-8 punctuation such as an em
    dash decodes to a curly quote there, which PowerShell treats as a string
    delimiter. Keep it ASCII.

.PARAMETER QtRoot
    Root of the Qt online-installer tree. Defaults to C:\Qt.

.PARAMETER Arch
    Kit architecture directory name. Defaults to msvc2022_64.

.PARAMETER OutputDirectory
    Where to write the triplet files. Defaults to the triplets folder next to
    this script.

.EXAMPLE
    .\New-DsqtTriplet.ps1
    Writes x64-windows-qt6-10-2.cmake (etc) for every kit found under C:\Qt.
    Dots are flattened to hyphens because vcpkg triplet names may only contain
    lowercase alphanumerics and hyphens.

.EXAMPLE
    .\New-DsqtTriplet.ps1 -OutputDirectory C:\dev\MyApp\triplets
    Writes them straight into a consuming project's overlay-triplets folder.
#>
[CmdletBinding()]
param(
    [string] $QtRoot = 'C:\Qt',
    [string] $Arch = 'msvc2022_64',
    [string] $OutputDirectory = (Join-Path $PSScriptRoot 'triplets')
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $QtRoot)) {
    throw "Qt root '$QtRoot' does not exist. Pass -QtRoot if Qt is installed elsewhere."
}

# A kit directory looks like C:\Qt\6.10.2\msvc2022_64
$kits = Get-ChildItem -LiteralPath $QtRoot -Directory |
    Where-Object { $_.Name -match '^\d+\.\d+' } |
    Where-Object { Test-Path (Join-Path $_.FullName $Arch) } |
    Sort-Object { [version]($_.Name -replace '[^\d.].*$', '') }

if (-not $kits) {
    throw "No Qt kits with an '$Arch' directory found under '$QtRoot'."
}

New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null

# vcpkg triplet names are restricted to lowercase alphanumerics and hyphens, so
# the dots in a Qt version have to be flattened: 6.10.2 -> qt6-10-2.
# DSQT_QT_VERSION inside the file keeps the real dotted version.
function Get-TripletName([string] $Version) {
    return 'x64-windows-qt' + ($Version -replace '\.', '-')
}

# Single source of truth for triplet text. Keep in step with the committed
# copies under triplets/ (regenerate them if you change this).
function New-TripletText([string] $Version, [string] $Root, [string] $KitArch) {
    $rootFwd = $Root -replace '\\', '/'
    return @"
# DsQt triplet - x64 Windows, MSVC 2022, Qt $Version
#
# Generated by Library/vcpkg/New-DsqtTriplet.ps1.
#
# vcpkg's ABI hash includes the text of this file, so DSQT_QT_VERSION below is
# what gives this Qt kit its own slot in the binary cache. DsQt is compiled once
# per (version x compiler x kit) and reused from then on. Editing this file
# invalidates that cache entry, which is the intended behaviour.

set(VCPKG_TARGET_ARCHITECTURE x64)
set(VCPKG_CRT_LINKAGE dynamic)
set(VCPKG_LIBRARY_LINKAGE dynamic)

# --- Per-port linkage -------------------------------------------------------
# toml++ is a private implementation detail of Dsqt::Core and is linked
# statically, so there is no tomlplusplus.dll to deploy and no dllimport
# requirement pushed onto anyone who links Dsqt::Core.
#
# The CRT stays dynamic: the official Qt kits are built against it.
if(PORT STREQUAL "tomlplusplus")
    set(VCPKG_LIBRARY_LINKAGE static)
endif()

# --- Qt kit -----------------------------------------------------------------
# Must match a kit installed by the Qt online installer / Maintenance Tool.
# The dsqt port fails with an explanatory message if the kit is missing, rather
# than quietly falling back to another version.
set(DSQT_QT_VERSION "$Version")
set(DSQT_QT_ROOT    "$rootFwd")
set(DSQT_QT_ARCH    "$KitArch")
"@
}

foreach ($kit in $kits) {
    $version = $kit.Name
    $name = Get-TripletName $version
    $path = Join-Path $OutputDirectory "$name.cmake"
    $content = New-TripletText -Version $version -Root $QtRoot -KitArch $Arch

    # ASCII + LF, so the file is byte-stable across machines and git settings.
    # The bytes matter: they feed vcpkg's ABI hash.
    $bytes = [Text.Encoding]::ASCII.GetBytes(($content -replace "`r`n", "`n"))
    [IO.File]::WriteAllBytes($path, $bytes)
    Write-Host "Wrote $path"
}

$latest = Get-TripletName $kits[-1].Name
Write-Host ''
Write-Host 'Point your project at these triplets in vcpkg-configuration.json:'
Write-Host ''
Write-Host '  {'
Write-Host ('    "overlay-triplets": ["' + ($OutputDirectory -replace '\\', '/') + '"]')
Write-Host '  }'
Write-Host ''
Write-Host 'then configure with, for example:'
Write-Host ("  cmake --preset ninja -DVCPKG_TARGET_TRIPLET=$latest")
